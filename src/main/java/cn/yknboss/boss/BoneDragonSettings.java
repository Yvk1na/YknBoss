    private static long seconds(double value) {
        return Math.max(1L, Math.round(value * 20.0));
    }

    private static double positive(double value, String path) {
        if (!Double.isFinite(value) || value <= 0.0) throw new IllegalArgumentException("bone-dragon." + path + " 必须大于 0");
        return value;
    }

    private static double nonNegative(double value, String path) {
        if (!Double.isFinite(value) || value < 0.0) throw new IllegalArgumentException("bone-dragon." + path + " 不能小于 0");
        return value;
    }

    private static double between(double value, double min, double max, String path) {
        if (!Double.isFinite(value) || value < min || value > max) {
            throw new IllegalArgumentException("bone-dragon." + path + " 必须在 " + min + " 到 " + max + " 之间");
        }
        return value;
    }

    private static double clamp(double value, double min, double max) {
        if (!Double.isFinite(value)) return max;
        return Math.max(min, Math.min(max, value));
    }
